# Builds src/lib/core.js from the current app.js, so the Svelte UI runs on exactly the same logic
# (sync, bridges, inbox states, sending, reactions). Rerun after app.js changes:
#   python3 make-core.py ../app/app.js src/lib/core.js
# Only the UI is new; render() becomes a notification the Svelte components listen to.
import re
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src).read().split('\n')
view_start = next(i for i, l in enumerate(lines) if l.startswith('// ') and l.rstrip().endswith(' view') and '----' in l)
core = lines[:view_start]
# The calendar (app/calendar.js and its panel) is not in the Svelte UI yet: no import, and no-ops for the core's calls.
core = [l for l in core if not l.startswith('import * as Cal ')] + ['const flushCal = () => {};', 'const loadCalendar = () => {};']

# Helpers that live among the old view code but hold no markup.
NAMES = ['titleOf', 'firstName', 'hue', 'initialsOf', 'BOXES', 'inBox', 'setBox', 'APPS', 'hiddenApps', 'toggleApp',
         'visibleEntries', 'entryOf', 'selectedEntry', 'selectAfter', 'moveSelection', 'nextUnread', 'archiveAllRead',
         'quickReacts', 'toggleReact', 'jumpTo', 'LINKS', 'prov', 'refreshLinks', 'norm', 'wordsOf', 'snippet', 'replyToLast', 'setShowAll']


def block(name):
    start = next((i for i, l in enumerate(lines) if re.match(rf'^(async )?function {name}\b|^const {name}\b', l)), None)
    if start is None:
        sys.exit(f'not found: {name}')
    first = lines[start]
    # One-line const, or a block that ends at the first line closing it at column 0.
    if first.startswith('const ') and first.rstrip().endswith(';') and not first.rstrip().endswith('=> {'):
        if first.count('(') == first.count(')') and first.count('[') == first.count(']') and first.count('{') == first.count('}'):
            return [first]
    end = start + 1
    if first.startswith('const ') and not first.rstrip().endswith(('{', '[', '(')):
        # A multi-line expression: it ends with the first line that ends the statement.
        while end < len(lines) and not lines[end].rstrip().endswith(';'):
            end += 1
        top = start
        while top > 0 and (lines[top - 1].startswith('/**') or lines[top - 1].startswith('//')):
            top -= 1
        return lines[top:end + 1]
    while end < len(lines) and not re.match(r'^(\}|\};|\];|\)\);?)\s*$', lines[end]):
        end += 1
    # A doc comment right above belongs to it.
    top = start
    while top > 0 and (lines[top - 1].startswith('/**') or lines[top - 1].startswith('//')):
        top -= 1
    return lines[top:end + 1]


extra = []
for n in NAMES:
    extra += [''] + block(n)

body = '\n'.join(core + extra)
# The old view's render and show become notifications; the Svelte app subscribes with onRender.
shim = '''
// ------------------------------------------------------------------ Svelte bridge
const listeners = new Set();
let queued = false;
/** Was the old app's DOM rebuild; now tells the Svelte UI that state changed (once per frame). */
function render() {
  if (queued) return;
  queued = true;
  requestAnimationFrame(() => { queued = false; for (const fn of listeners) fn(); });
}
function show(view) { S.view = view; render(); }
const onRender = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };
'''
names = sorted(set(re.findall(r'^(?:async )?function (\w+)|^const (\w+)|^let (\w+)|^class (\w+)', body, re.M) and
                   [m for g in re.findall(r'^(?:async )?function (\w+)|^const (\w+)|^let (\w+)|^class (\w+)', body, re.M) for m in g if m]))
names += ['render', 'show', 'onRender']
header = '// Generated by make-core.py from app.js: edit app.js, then rerun. Do not edit by hand.\n'
open(out, 'w').write(header + body + '\n' + shim + '\nexport { ' + ', '.join(names) + ' };\n')
print(len(names), 'exports')
