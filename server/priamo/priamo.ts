#!/usr/bin/env bun
// Weft Priamo: who may reach this homeserver over Yggdrasil.
//
//   bun priamo.ts render <priamo.json> <out dir>
//
// priamo.json lists the contacts whose servers may federate with this one:
//   { "interface": "ygg0", "port": 8448,
//     "contacts": [{ "name": "Example", "address": "201:db8::1" }] }
// It writes two files from that one list, so the firewall and the homeserver always agree:
//   priamo.nft         nftables: on the Yggdrasil interface only the contacts reach the federation port, and
//                      200::/7 never leaves through another interface (the overlay vouches for those addresses only
//                      while the overlay carries them; Tuwunel's yggdrasil_trust_overlay relies on that)
//   allowlist.toml     Tuwunel's allowed_remote_server_names_experimental for the same contacts (reloadable)
// Apply with `nft -f priamo.nft` (root) and pass allowlist.toml to Tuwunel as a second `-c`.
// A contact's server name must be its address as Yggdrasil prints it (lower case, zeros compressed): another
// spelling of the same address is refused. A removed contact is refused at once by the reloaded allowlist; the
// firewall stops only its new connections.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { isIPv6 } from 'node:net';
import { join } from 'node:path';

export type Contact = { name: string; address: string };
export type Priamo = { interface: string; port: number; contacts: Contact[] };

/** The address in the form a server name carries it: lower case, zeros compressed (RFC 5952). */
export function canonical(address: string): string {
  const bare = address.trim().replace(/^\[|\]$/g, '');
  if (!isIPv6(bare)) throw new Error(`nie je IPv6 adresa: ${address}`);
  const host = new URL(`http://[${bare}]/`).hostname.slice(1, -1);
  if ((Number.parseInt(host.split(':')[0] || '0', 16) & 0xfe00) !== 0x0200) {
    throw new Error(`nie je adresa Yggdrasilu (200::/7): ${address}`);
  }
  return host;
}

export function parse(text: string): Priamo {
  const raw: unknown = JSON.parse(text);
  if (typeof raw !== 'object' || raw === null) throw new Error('priamo.json nie je objekt');
  const o = raw as Record<string, unknown>;
  const iface = o.interface ?? 'ygg0';
  const port = o.port ?? 8448;
  if (typeof iface !== 'string' || !/^[\w.-]{1,15}$/.test(iface)) throw new Error('zlé rozhranie');
  if (typeof port !== 'number' || !Number.isInteger(port) || port < 1 || port > 65535) throw new Error('zlý port');
  if (!Array.isArray(o.contacts)) throw new Error('chýba zoznam contacts');
  const seen = new Set<string>();
  const contacts = o.contacts.map((c: unknown) => {
    const { name, address } = (c ?? {}) as Record<string, unknown>;
    if (typeof name !== 'string' || typeof address !== 'string') throw new Error('kontakt potrebuje name a address');
    const a = canonical(address);
    if (seen.has(a)) throw new Error(`kontakt dvakrát: ${a}`);
    seen.add(a);
    return { name, address: a };
  });
  return { interface: iface, port, contacts };
}

export function nft(p: Priamo): string {
  const set = p.contacts.length
    ? `\t\telements = { ${p.contacts.map((c) => c.address).join(', ')} }\n`
    : '';
  // Delete-then-create keeps a re-render atomic: `nft -f` applies the whole file or nothing.
  return `table inet weft_priamo
delete table inet weft_priamo
table inet weft_priamo {
\tset contacts {
\t\ttype ipv6_addr
${set}\t}

\tchain input {
\t\ttype filter hook input priority -10; policy accept;
\t\tiifname "${p.interface}" ct state established,related accept
\t\tiifname "${p.interface}" ip6 saddr @contacts tcp dport ${p.port} accept
\t\tiifname "${p.interface}" drop
\t}

\tchain output {
\t\ttype filter hook output priority -10; policy accept;
\t\tip6 daddr 200::/7 oifname != { "${p.interface}", "lo" } reject
\t}
}
`;
}

const escapeRegex = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function allowlist(p: Priamo): string {
  // Tuwunel matches the server name's host, the bracketed address; a port is allowed too in case that changes.
  // TOML literal strings keep the backslashes.
  const names = p.contacts.map((c) => `'^\\[${escapeRegex(c.address)}\\](:[0-9]+)?$'`);
  // An empty list would allow every server, so no contacts means a pattern nothing matches.
  const list = names.length ? names.join(', ') : `'^$'`;
  return `# Generated by server/priamo/priamo.ts from priamo.json; edit that file instead.
[global]
allowed_remote_server_names_experimental = [${list}]
`;
}

if (import.meta.main) {
  const [cmd, file, out] = process.argv.slice(2);
  if (cmd !== 'render' || !file || !out) {
    console.error('použitie: bun priamo.ts render <priamo.json> <priečinok>');
    process.exit(2);
  }
  const p = parse(readFileSync(file, 'utf8'));
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'priamo.nft'), nft(p));
  writeFileSync(join(out, 'allowlist.toml'), allowlist(p));
  console.log(`${p.contacts.length} kontaktov → ${join(out, 'priamo.nft')}, ${join(out, 'allowlist.toml')}`);
}
